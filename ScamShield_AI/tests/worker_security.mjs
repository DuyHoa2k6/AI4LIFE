import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let listener,onUpdated,onRemoved,failure=null,blockFetch=false,releaseFetch=null;const requests=[];
const context=vm.createContext({AbortController,AbortSignal,setTimeout,clearTimeout,Map,
  chrome:{runtime:{id:'test-extension',onMessage:{addListener:fn=>listener=fn}},tabs:{onUpdated:{addListener:fn=>onUpdated=fn},onRemoved:{addListener:fn=>onRemoved=fn}}},
  fetch:async(url,options)=>{requests.push({url,options});if(blockFetch)await new Promise(resolve=>releaseFetch=resolve);return failure?{ok:false,status:422,json:async()=>failure}:{ok:true,json:async()=>({risk_status:'clear'})};}});
vm.runInContext(fs.readFileSync(path.join(root,'extension/worker.js'),'utf8'),context);
const sender={id:'test-extension',tab:{id:4},frameId:0,documentId:'doc-A',url:'https://fixture.example/'};
const send=(m,s=sender)=>new Promise(resolve=>{if(!listener(m,s,resolve))resolve(null);});
const checks=[];const check=(name,condition)=>{assert.ok(condition,name);checks.push({name,passed:true});};
check('reject different extension',await send({type:'SS_CONFIG'},{...sender,id:'attacker'})===null);
check('reject iframe sender',await send({type:'SS_CONFIG'},{...sender,frameId:1})===null);
check('reject popup as analysis sender',await send({type:'SS_ANALYZE',text:'x'},{id:'test-extension'})===null);
await send({type:'SS_OPEN',session:'session-A'});
check('reject wrong document',!(await send({type:'SS_ANALYZE',session:'session-A',text:'x'},{...sender,documentId:'doc-B'})).ok);
check('reject wrong session',!(await send({type:'SS_ANALYZE',session:'session-B',text:'x'})).ok);
check('reject changed page URL',!(await send({type:'SS_ANALYZE',session:'session-A',text:'x'},{...sender,url:'https://fixture.example/new'})).ok);
await send({type:'SS_ANALYZE',session:'session-A',itemId:'one',version:1,text:'input text',url:'http://evil.example'});
check('API destination fixed',requests.at(-1).url==='http://127.0.0.1:8000/api/analyze');
check('wire payload only text',JSON.stringify(JSON.parse(requests.at(-1).options.body))==='{"text":"input text"}');
check('configuration announces payload protocol', (await send({type:'SS_CONFIG'})).protocol===2);
const linked={text:'https://example.invalid',links:[{id:'u',message_id:'m1',url:'https://example.invalid',display_text:'https://example.invalid'}]};
check('linked payload accepted and preserved',(await send({type:'SS_ANALYZE',session:'session-A',payload:linked})).ok&&JSON.stringify(JSON.parse(requests.at(-1).options.body))===JSON.stringify(linked));
failure={code:'INVALID_INPUT',diagnostic:{issues:[{path:['body','links',0,'start','SECRET_KEY']}]},message:'SECRET_VALUE'};
const invalid=await send({type:'SS_ANALYZE',session:'session-A',payload:linked});
check('422 shows safe field path instead of generic invalid input',!invalid.ok&&invalid.error.includes('links.0.start')&&!invalid.error.includes('SECRET'));
failure=null;
onUpdated(4,{url:'https://fixture.example/new'});
check('navigation revokes session',!(await send({type:'SS_ANALYZE',session:'session-A',text:'x'})).ok);
await send({type:'SS_OPEN',session:'session-C'});onRemoved(4);
check('tab close revokes session',!(await send({type:'SS_ANALYZE',session:'session-C',text:'x'})).ok);
await send({type:'SS_OPEN',session:'session-D'});blockFetch=true;
const pending=send({type:'SS_ANALYZE',session:'session-D',itemId:'old',version:1,text:'old input'});
while(!releaseFetch)await new Promise(resolve=>setTimeout(resolve,0));
await send({type:'SS_OPEN',session:'session-E'});blockFetch=false;releaseFetch();
const late=await pending;
check('late response from replaced session rejected',!late.ok&&late.error==='STALE_SESSION');
const out=process.env.SCAMSHIELD_REPORT_DIR?path.resolve(process.env.SCAMSHIELD_REPORT_DIR):path.join(root,'reports/week2');
fs.mkdirSync(out,{recursive:true});fs.writeFileSync(path.join(out,'worker_security.json'),JSON.stringify({mode:'isolated worker unit test with simulated chrome APIs',checks},null,2));
console.log(`${checks.length} worker security checks passed`);
